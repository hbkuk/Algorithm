-- 메인 쿼리: MEMBER_ID 에 해당하는 전체 리뷰 조회
-- 서브 쿼리: REST_REVIEW 테이블에서 MEMBER_ID MAX 값 확인.
SELECT 
    p.MEMBER_NAME as MEMBER_NAME, 
    r.REVIEW_TEXT as REVIEW_TEXT, 
    r.REVIEW_DATE as REVIEW_DATE
FROM MEMBER_PROFILE p JOIN REST_REVIEW r ON p.MEMBER_ID = r.MEMBER_ID
WHERE p.MEMBER_ID = (
    SELECT MEMBER_ID
    FROM REST_REVIEW
    GROUP BY MEMBER_ID
    ORDER BY COUNT(*) DESC
    LIMIT 1
)
ORDER BY REVIEW_DATE, REVIEW_TEXT